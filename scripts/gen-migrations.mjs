// Regenerates lib/migrations.generated.ts from supabase/migrations/*.sql.
// Run after adding a migration: node scripts/gen-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from "fs";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => {
  const sql = readFileSync(`${dir}/${f}`, "utf8");
  return `  { id: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },`;
});
writeFileSync(
  "lib/migrations.generated.ts",
  `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n` +
    `export const MIGRATIONS: { id: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`
);
console.log(`generated manifest for ${files.length} migrations`);
